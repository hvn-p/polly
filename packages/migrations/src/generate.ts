// `nr generate`: brings the worktree's test database to the shipped migrations,
// then writes into @polly/database the table types read from it (kysely-codegen,
// without DBOS's schema nor the migration bookkeeping) and the name of the last
// migration, which the schema check compares with the database. CI reruns it
// and fails on a difference.

import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { environment } from '@polly/platform'
import type { Migration } from 'kysely/migration'
import { connect } from './connect.ts'
import { migrate } from './migrate.ts'
import { migrations as shipped } from './migrations/index.ts'
import { testDatabaseUrl } from './test-database.ts'

const GENERATED = join(import.meta.dirname, '..', '..', 'database', 'src', 'generated')

export function lastMigrationModule(migrations: Record<string, Migration>): string {
  const last = Object.keys(migrations).sort().at(-1) ?? ''
  return `// Generated by nr generate: the last migration the table types were read after.\nexport const LAST_MIGRATION = '${last}'\n`
}

if (process.argv[1] === import.meta.filename) {
  const url = testDatabaseUrl(environment())
  const db = connect(url)
  try {
    await migrate(db)
  } finally {
    await db.destroy()
  }
  execFileSync(
    'kysely-codegen',
    [
      '--dialect=postgres',
      `--url=${url}`,
      '--default-schema=public',
      '--exclude-pattern=(dbos.*|kysely_migration*)',
      `--out-file=${join(GENERATED, 'tables.ts')}`,
      '--log-level=error',
    ],
    { stdio: 'inherit' },
  )
  writeFileSync(join(GENERATED, 'last-migration.ts'), lastMigrationModule(shipped))
  // In the repository's style, so a regeneration differs only where the schema does.
  execFileSync('biome', ['format', '--write', GENERATED], { stdio: 'inherit' })
}
